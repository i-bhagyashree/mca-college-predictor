    const S = F ? F.scale_assumed : 1, k = (PL_LIST ? PL_LIST.n : PR_N) / S;   // forecast ranks → the planner's rank scale (inverse of the position)
    const info = new Map();
    for (const c of D.colleges) {
      const id = c.college_id, lp = last.get(id), mp = ml.get(id);
      if (!lp && !mp) continue;
      const e = { id, min };
      if (lp) {
        const open = isOpen(lp.cl, PL_SCALE);
        e.last = { cl: lp.cl, pool: lp, open, likely: open ? min : need(lp.cl), safe: open ? min : need(0.8 * lp.cl) };
        if (me.rank != null) e.last.band = open && me.rank <= PL_SCALE ? "open" : bandOf(me.rank, lp.cl);
      }
      if (mp) {
        const open = isOpen(mp.cl, S);
        e.ml = { cl: mp.cl, lo: mp.lo, hi: mp.hi, pool: mp, open,
                 likely: open ? min : need(mp.cl * k), safe: open ? min : need(0.8 * mp.cl * k),
                 pctHi: open ? min : need(mp.lo * k), pctLo: open ? min : need(mp.hi * k) };
        if (me.rankMl != null) e.ml.band = open && me.rankMl <= S ? "open" : bandOf(me.rankMl, mp.cl);
      }
      e.sortKey = e.ml ? e.ml.likely : e.last.likely;
      info.set(id, e);
    }
    plCache = { key, info };
    return info;
