  /* best eligible pool per college from a list of seat pools */
  function bestPerCollege(pools, me) {
    const best = new Map();
    for (const p of pools) {
      if (!eligible(p, me)) continue;
      const b = best.get(p.c);
      if (!b || p.cl > b.cl) best.set(p.c, p);
    }
    return best;
  }

  /* ---- Rank predictor ---- */
  function historical(me, rd, choice) {
    const ys = yearsFor(rd);
    if (!/^last/.test(choice)) {                       // one exact past year
      const y = +choice;
      const list = [...bestPerCollege(aggregate(rows.filter((r) => r.y === y && r.r === rd)), me).values()]
        .map((p) => {
          const last = scaleOf(y, rd);
          return { ...p, kind: "year", band: isOpen(p.cl, last) && me.rank <= last ? "open" : bandOf(me.rank, p.cl) };
        });
      return { list, label: `${y} ${ROUND[rd]}`, years: [y] };
    }
    const win = ys.slice(0, choice === "last5" ? 5 : 3);
    const base = scaleOf(win[0], rd);
    const per = new Map();
    for (const y of win) {
      const f = base / scaleOf(y, rd);                // adjust older ranks to the latest year's scale
      for (const p of bestPerCollege(aggregate(rows.filter((r) => r.y === y && r.r === rd)), me).values()) {
        const e = per.get(p.c) || { c: p.c, hist: [], latest: p };
        e.hist.push({ y, cl: p.cl, adj: Math.round(p.cl * f), f, open: isOpen(p.cl, scaleOf(y, rd)) });
        per.set(p.c, e);
      }
    }
    const list = [...per.values()].map((e) => {
      const adj = e.hist.map((h) => h.adj);
      const hits = e.hist.filter((h) => me.rank <= h.adj).length, n = e.hist.length;
      const allOpen = e.hist.every((h) => h.open) && me.rank <= base;
      const band = allOpen ? "open" : n === 1 ? bandOf(me.rank, adj[0])
        : hits === n ? "safe" : hits / n >= 0.5 ? "likely" : hits > 0 ? "reach" : "unlikely";
      return { ...e.latest, c: e.c, kind: "multi", hist: e.hist, hits, n, band,
               cl: Math.round(adj.reduce((a, b) => a + b, 0) / n), lo: Math.min(...adj), hi: Math.max(...adj) };
    });
    return { list, label: `${ROUND[rd]}, ${win.at(-1)}–${win[0]}`, years: win, base };
  }

  /* ---- ML predictor ---- */
  /* Seat chance (ML page only): the chance that next year's closing rank is at or after your rank.
     The forecast gives the 10th percentile (lo), the middle (mid) and the 90th percentile (hi) of
     the closing rank, so a rank equal to lo has ~90%, mid ~50% and hi ~10%; in between it is
     interpolated, and it is capped at 1–99% outside the range. */
  function seatChance(rank, lo, mid, hi) {
    const a = Math.max(1, mid - lo), b = Math.max(1, hi - mid);
    const p = rank <= lo ? 0.9 + 0.09 * Math.min(1, (lo - rank) / a)
      : rank <= mid ? 0.5 + 0.4 * (mid - rank) / a
      : rank <= hi ? 0.1 + 0.4 * (hi - rank) / b
      : 0.1 - 0.09 * Math.min(1, (rank - hi) / b);
    return Math.round(p * 100);
  }
  function machineLearning(me) {
    const pools = F.pools.map((p) => ({ c: p.c, y: F.target_year, r: "R1", s: p.s, k: "X", g: p.g, d: null, cv: 0,
      o: null, cl: p.rank, lo: p.lo, hi: p.hi, n: null, kind: "ml", last_rank: p.last_rank, last_year: p.last_year,
      n_years: p.n_years, srcs: [] }));
    const S = F.scale_assumed;
    const latest = +Object.keys(F.scale_by_year).at(-1);
    const list = [...bestPerCollege(pools, me).values()].map((p) => {
      const band = isOpen(p.cl, S) && me.rank <= S ? "open" : bandOf(me.rank, p.cl);
      // the same college judged by last year's ACTUAL cut-off, i.e. what the Rank Predictor shows
      const sly = F.scale_by_year[String(p.last_year)], lastAdj = Math.round(p.last_rank * S / sly);
      const lastBand = p.last_year !== latest ? null
        : isOpen(p.last_rank, sly) && me.rank <= S ? "open" : bandOf(me.rank, lastAdj);
      const diff = p.cl - lastAdj;
      return { ...p, band, lastBand, lastAdj, trend: diff < 0 ? "harder" : diff > 0 ? "easier" : "same",
               chance: seatChance(me.rank, p.lo, p.cl, p.hi) };
    });
    return { list, label: `${F.target_year} Round 1 (ML forecast)`, years: [F.target_year] };
  }

