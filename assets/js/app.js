  const yearsFor = (rd) => [...new Set(rows.filter((r) => r.r === rd).map((r) => r.y))].sort((a, b) => b - a);

  /* Percentage → rank (pipeline/rank_from_percentage.py). Built from the latest list that prints
     both merit percentage and rank (2026 Round 2): ~200 (percentage, rank) points on one merit list.
     A student's rank is interpolated between neighbouring points. */
  const PR = D.pct_rank || null;
  /* Size of the merit list the percentage → rank curve comes from (its last rank). A student's
     POSITION is rank ÷ this size, so it stays between 0 and 1. (Dividing by Round 1's last allotted
     rank, which is smaller, put the bottom of the list above 100% and beyond next year's forecast list.) */
  const PR_N = PR ? Math.max(...PR.points.map((p) => p[1])) : 1;
  function rankFromPct(pct) {
    const pts = PR.points;                          // [[percentage ascending, rank], ...]
    const pLo = pts[0][0], pHi = pts.at(-1)[0];
    let r;
    if (pct >= pHi) r = pts.at(-1)[1];
    else if (pct <= pLo) r = pts[0][1];
    else {
      const i = pts.findIndex((p) => p[0] >= pct);
      const [p1, r1] = pts[i - 1], [p2, r2] = pts[i];
      r = r1 + (r2 - r1) * (pct - p1) / (p2 - p1);
    }
    const rank = Math.max(1, Math.round(r)), err = Math.ceil(PR.accuracy.p90_abs_ranks);
    return { pct, rank, lo: Math.max(1, rank - err), hi: rank + err, below: pct < pLo, above: pct > pHi, pos: Math.min(1, rank / PR_N) };
  }

  /* Official MP-DTE merit lists (pipeline/merit_lists.py): for every percentage, the first and last rank
     that had it. Only percentage and rank are stored, no names. The Rank Predictor reads your rank from the
     list of the SAME year and round as the cut-offs it compares with, so both come from one counselling. */
  const MERIT = (D.merit && D.merit.lists) || [];
