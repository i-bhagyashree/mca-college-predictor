  const PL_YEAR = Math.max(...rows.filter((r) => r.r === "R1").map((r) => r.y));     // last year with Round 1
  const PL_SCALE = scaleOf(PL_YEAR, "R1");
  const plLastPools = aggregate(rows.filter((r) => r.y === PL_YEAR && r.r === "R1"));
